#!/usr/bin/env python3
"""Reproduce BiblePath's Dutch Catholic reading edition from reviewed sources.

Canisius 1939 is the base translation. Its eBible transcription lacks the
Greek additions to Esther and Daniel 3; the original CC0 OSIS supplies those
passages. Esther 15:1 and 16, absent from both electronic transcriptions, are
supplied by the separately attributed historical Catholic Van Oers translation.
No scripture wording is translated or generated by this importer.
"""
import argparse
import copy
import hashlib
import importlib.util
import json
import pathlib
import urllib.request
import xml.etree.ElementTree as ET
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("catholic_import", ROOT / "scripts" / "import-catholic-bible.py")
CATHOLIC = importlib.util.module_from_spec(spec)
spec.loader.exec_module(CATHOLIC)
BIBLE = CATHOLIC.BIBLE
ORDER, GROUPS, NAMES, ALIASES = CATHOLIC.ORDER, CATHOLIC.GROUPS, CATHOLIC.NAMES, CATHOLIC.ALIASES
BASE_URL = "https://ebible.org/Scriptures/nld1939_usfx.zip"
BASE_SHA256 = "08d8647b5bd0fc9cdf5043aadabc904fb165cb2575b0f369afd64ea3f695abc8"
BASE_XML_SHA256 = "393cf0dda92b51541e298a9ad2298fb722d8875e3e979f2dfb3cb58a698c3795"
OSIS_COMMIT = "70838411d24086ccb5761712af4949604a390e4a"
OSIS_URL = f"https://raw.githubusercontent.com/Isidore-Guild/Canisius/{OSIS_COMMIT}/canisius.xml"
OSIS_SHA256 = "9742d2fd460155af9e7eeb21719badfe8965ae8cc40219e960840edf682cc712"
SUPPLEMENT = ROOT / "scripts" / "catholic-dutch-supplement.json"
SUPPLEMENT_SHA256 = "01575cf327d5ef887c9909f0a0803256c64836797b18ed1d280750b21cb01951"
DESTINATION = ROOT / "dist" / "catholic-bible-data-nl.json"
NS = {"o": "http://www.bibletechnologies.net/2003/OSIS/namespace"}
OSIS_SOURCE = "canisius-osis-7083841"
# Only independently matched notes are copied across the differing source
# numbering systems. In particular, Psalms cannot be mapped by equal numbers.
VARIANT_NOTES = {
    ("GEN", 49, 18): "Gen.49.18", ("LEV", 11, 25): "Lev.11.25",
    ("JOS", 3, 12): "Josh.3.12", ("JOS", 10, 15): "Josh.10.15",
    ("1KI", 15, 6): "1Kgs.15.6", ("1KI", 15, 32): "1Kgs.15.32",
    ("JOB", 12, 22): "Job.12.22", ("JOB", 13, 28): "Job.13.28", ("JOB", 27, 1): "Job.27.1",
    ("PSA", 116, 18): "Ps.115.9", ("PSA", 118, 20): "Ps.117.20",
    ("ISA", 2, 1): "Isa.2.1", ("ISA", 60, 12): "Isa.60.12",
    ("JER", 15, 13): "Jer.15.14", ("JER", 15, 14): "Jer.15.14",
    ("JER", 16, 14): "Jer.16.15", ("JER", 16, 15): "Jer.16.15",
    ("EZK", 40, 30): "Ezek.40.30",
}


def download(path, url):
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 BiblePath source importer"})
        with urllib.request.urlopen(request, timeout=60) as response:
            path.write_bytes(response.read())
    return path


def checked_bytes(path, expected):
    raw = path.read_bytes()
    actual = hashlib.sha256(raw).hexdigest()
    if actual != expected:
        raise ValueError(f"Source checksum changed for {path.name}: {actual}; review before changing the pin.")
    return raw


def osis_text(element):
    if element.tag.rsplit("}", 1)[-1] == "note":
        return ""
    return (element.text or "") + "".join(osis_text(child) + (child.tail or "") for child in element)


def osis_chapters(document, book):
    """Read nested chapters, retaining translation notes separately from scripture."""
    chapters = []
    for chapter in document.findall(f'.//o:div[@osisID="{book}"]//o:chapter', NS):
        chapter_number = int(chapter.get("osisID").split(".")[1])
        verses = []
        for verse in chapter.findall("o:verse", NS):
            verse_number = int(verse.get("osisID").split(".")[2])
            item = {"number": verse_number, "text": BIBLE.clean(osis_text(verse)), "sourceEdition": OSIS_SOURCE}
            notes = [BIBLE.clean("".join(note.itertext())) for note in verse.findall(".//o:note", NS)]
            if notes:
                item["notes"] = notes
            verses.append(item)
        if len({verse["number"] for verse in verses}) != len(verses):
            raise ValueError(f"Duplicate verse in {book} {chapter_number}")
        headings = [{"text": BIBLE.clean(osis_text(title)), "beforeVerse": verses[0]["number"], "kind": "heading", "sourceEdition": OSIS_SOURCE} for title in chapter.findall("o:title", NS)]
        chapters.append({"number": chapter_number, "headings": headings, "verses": verses})
    return chapters


def import_dutch(base, osis, supplement=SUPPLEMENT):
    base_raw = checked_bytes(base, BASE_SHA256)
    with zipfile.ZipFile(base) as archive:
        xml = archive.read("nld1939_usfx.xml")
    assert hashlib.sha256(xml).hexdigest() == BASE_XML_SHA256
    document = ET.fromstring(xml)
    osis_document = ET.fromstring(checked_bytes(osis, OSIS_SHA256))
    supplement_raw = checked_bytes(supplement, SUPPLEMENT_SHA256)
    reviewed = json.loads(supplement_raw)
    source_ids = [b.get("id") for b in document.findall("book")]
    assert len(source_ids) == 73 and set(source_ids) == set(ORDER) - {"DAN"} | {"DAG"}
    books = []
    for index, book_id in enumerate(ORDER):
        source_id = "DAG" if book_id == "DAN" else book_id
        element = copy.deepcopy(document.find(f"book[@id='{source_id}']"))
        bridges = {}
        for verse in element.findall(".//v"):
            if "-" in verse.get("id"):
                start, end = map(int, verse.get("id").split("-"))
                chapter = int(verse.get("bcv").split(".")[1])
                bridges[(chapter, start)] = end
                verse.set("id", str(start))
        book = BIBLE.parse_book(element, book_id, NAMES[book_id], "OT" if index < 46 else "NT")
        book["group"] = next(group for group, ids in GROUPS.items() if book_id in ids)
        book["sourceEdition"] = "nld1939"
        if book_id in ALIASES:
            book["aliases"] = ALIASES[book_id]
        for chapter in book["chapters"]:
            for verse in chapter["verses"]:
                if (chapter["number"], verse["number"]) in bridges:
                    verse["endNumber"] = bridges[(chapter["number"], verse["number"])]
                    verse["numberLabel"] = f"{verse['number']}–{verse['endNumber']}"
        books.append(book)
    by_id = {book["id"]: book for book in books}

    # The OSIS explicitly marks this identical USFX prefix as a chapter title.
    # Move those exact words into the heading channel without losing content.
    judith_heading = BIBLE.clean(osis_text(osis_document.find('.//o:chapter[@osisID="Jdt.1"]/o:title', NS)))
    judith_start = by_id["JDT"]["chapters"][0]
    assert judith_start["verses"][0]["text"].startswith(judith_heading + " ")
    judith_start["verses"][0]["text"] = judith_start["verses"][0]["text"][len(judith_heading):].lstrip()
    assert judith_start["verses"][0]["text"].startswith("Toen Arpaksad,")
    judith_start["headings"].append({"text": judith_heading, "beforeVerse": 1, "kind": "heading", "sourceEdition": OSIS_SOURCE})

    # The Canisius wording includes the sentence about fire in water, but its
    # source does not label a verse span. Keep the source number, and explain
    # the visible numbering gap without asserting reference equivalence.
    wisdom_bridge = next(v for v in by_id["WIS"]["chapters"][15]["verses"] if v["number"] == 16)
    assert "Ja, nog wonderlijker: in het alles blussende water" in wisdom_bridge["text"]
    wisdom_bridge["notes"] = ["De Canisiusbron vervolgt na vers 16 met vers 18. De zin over het vuur in het alles blussende water is in de brontekst onder vers 16 opgenomen. Deze leeseditie behoudt de bronnummering."]
    maccabees_boundary = next(v for v in by_id["1MA"]["chapters"][8]["verses"] if v["number"] == 33)
    maccabees_boundary["notes"] = ["De gebruikte Canisiusbronnen vervolgen na 9:33 met 9:35 en bevatten geen afzonderlijk genummerd vers 9:34. Die bronnummering is hier behouden. Het bericht over Bakchides' achtervolging staat in 9:43; gelijke versnummers in andere vertalingen mogen niet zonder controle worden gelijkgesteld."]

    # eBible retains the translator's dash markers but omits explanatory
    # footnotes. Preserve those markers, expose their meaning, and recover
    # the original notes where the source correspondence has been reviewed.
    for book in books:
        for chapter in book["chapters"]:
            for verse in chapter["verses"]:
                if verse["text"] != "-":
                    continue
                verse["notes"] = ["De digitale Canisiusbron geeft op dit versnummer alleen een streepje, geen afzonderlijke bijbelzin. Dit teken is uit de bron overgenomen; het is geen laadfout."]
                source_ref = VARIANT_NOTES.get((book["id"], chapter["number"], verse["number"]))
                if source_ref:
                    original_verse = osis_document.find(f'.//o:verse[@osisID="{source_ref}"]', NS)
                    original_notes = original_verse.findall(".//o:note", NS)
                    assert original_notes, source_ref
                    verse["notes"].extend(BIBLE.clean("".join(note.itertext())) for note in original_notes)
                    verse["noteSourceEdition"] = OSIS_SOURCE
                    verse["noteSourceReference"] = source_ref

    # Replace the whole Daniel book: OSIS puts the final three opening verses
    # of eBible chapter 4 at 3:98–100. Replacing only chapter 3 would duplicate
    # them and silently misalign all subsequent chapter-4 references.
    by_id["DAN"]["chapters"] = osis_chapters(osis_document, "Dan")
    by_id["DAN"]["sourceEdition"] = OSIS_SOURCE
    esther = by_id["EST"]
    for chapter in osis_chapters(osis_document, "Esth"):
        if chapter["number"] == 10:
            esther["chapters"][9]["verses"].extend(v for v in chapter["verses"] if v["number"] >= 4)
        elif chapter["number"] > 10:
            esther["chapters"].append(chapter)

    # The supplement is a reviewed transcription, with verse-level attribution.
    # It is deliberately kept separate from the Canisius source files.
    for record in reviewed["verses"]:
        book = by_id[record["book"]]
        chapter = next((c for c in book["chapters"] if c["number"] == record["chapter"]), None)
        if chapter is None:
            chapter = {"number": record["chapter"], "headings": [], "verses": []}
            book["chapters"].append(chapter)
        old = next((v for v in chapter["verses"] if v["number"] == record["number"]), None)
        if old:
            assert (record["book"], record["chapter"], record["number"]) == ("EST", 15, 1)
            assert old["notes"] == ["Werd niet vertaald."]
            chapter["verses"].remove(old)
        chapter["verses"].append({"number": record["number"], "text": record["text"],
                                  "sourceEdition": "van-oers-1933", "sourceUrl": record["sourceUrl"],
                                  "notes": ["Bron: J. M. van Oers, De heilige boeken van het oude verbond, deel 3 (1933, ongewijzigde tweede druk), via DBNL. Deze passage ontbreekt in de gebruikte digitale Canisiusbronnen; daarom is hier deze oudere katholieke vertaling opgenomen."]})
        chapter["verses"].sort(key=lambda v: v["number"])
    for book in books:
        assert [c["number"] for c in book["chapters"]] == list(range(1, len(book["chapters"]) + 1))
        for chapter in book["chapters"]:
            numbers = [v["number"] for v in chapter["verses"]]
            assert numbers == sorted(set(numbers)), (book["id"], chapter["number"])
            assert all(v["text"] or v.get("notes") for v in chapter["verses"])
    assert len(by_id["EST"]["chapters"]) == 16
    assert len(by_id["DAN"]["chapters"][2]["verses"]) == 100
    assert len(reviewed["verses"]) == 25

    credit = "Catholic Bible in Dutch: Petrus Canisius translation (1939), with a separately credited supplement from the Catholic translation by J. M. van Oers (1933). Historical spelling; public domain."
    versification = "This reading edition preserves its sources’ numbering. Esther includes 10:4–16:24; Daniel includes the prayer and song in 3:24–90, Susanna in chapter 13 and Bel and the Dragon in chapter 14. The Letter of Jeremiah is Baruch 6. Psalm 84:9–10 is one combined text verse. Equal verse numbers in other translations do not automatically identify the same passage."
    meta = {
        "title": "Katholieke Bijbel — Nederlands", "abbreviation": "RK-NL", "editionId": "catholic-nl",
        "edition": "Nederlandse katholieke leeseditie — Canisius 1939 met bronvermelde aanvulling",
        "sourceEdition": "canisius-1939-with-van-oers-supplement", "canon": "catholic", "canonComplete": True,
        "language": "nl", "textDirection": "ltr", "license": "Public domain; CC0 for the Canisius OSIS transcription",
        "licenseUrl": "https://ebible.org/nld1939/copyright.htm", "sourcePage": "data-notes.html#dutch-catholic",
        "sourceUrl": BASE_URL, "sourceSha256": hashlib.sha256(base_raw).hexdigest(), "sourceXmlSha256": BASE_XML_SHA256,
        "downloadedAt": "2026-10-22", "credit": credit, "versificationNote": versification,
        "annotationNotice": "Atlas name links are editorial connections. Older atlas references have not been aligned verse by verse with this Dutch Catholic edition; a shared verse number does not establish identical text.",
        "processing": "All 73 Canisius USFX books are retained in Catholic order. Daniel is replaced in full by the pinned original Canisius OSIS text to include the prayer/song and preserve its chapter 3/4 boundary. Esther 10:4–15 comes from that OSIS; Esther 15:1 and chapter 16 are separately credited to Van Oers. Whitespace is normalized; source wording, punctuation and historical spelling are retained. Explicit OSIS chapter titles at Judith 1 and Daniel 13 are preserved as headings; Judith's identical title prefix is separated from USFX verse 1. Other editorial headings embedded in the source verse text are retained there. The Canisius edition's textual variants, 23 dash-marked verse positions and nonconsecutive verse numbering are preserved and explained in notes. Reviewed corresponding original OSIS notes are restored separately. The explicit source bridge Psalm 84:9–10 is displayed as a verse span. Wisdom 16 retains the source numbering gap at 17 with an explanatory note on 16. 1 Maccabees 9:34 has no separate source verse; its numbering gap is retained and explained at 9:33. Sirach retains the shorter source text and its nonconsecutive numbering. This is a composite reading edition, not a claim that the incomplete electronic Canisius sources are complete on their own.",
        "sources": [
            {"id": "nld1939", "title": "Petrus Canisiusvertaling (1939), eBible USFX", "url": BASE_URL, "sha256": BASE_SHA256, "xmlSha256": BASE_XML_SHA256, "license": "Public domain", "licenseUrl": "https://ebible.org/nld1939/copyright.htm"},
            {"id": OSIS_SOURCE, "title": "Petrus Canisiusvertaling, original OSIS transcription", "url": OSIS_URL, "sha256": OSIS_SHA256, "commit": OSIS_COMMIT, "license": "Public domain text; CC0-1.0 transcription", "licenseUrl": f"https://github.com/Isidore-Guild/Canisius/blob/{OSIS_COMMIT}/LICENSE", "scope": "Daniel 1–14; Esther 10:4–15:19 except 15:1; reviewed textual notes for dash-marked base verses"},
            {"id": "van-oers-1933", "title": "J. M. van Oers, De heilige boeken van het oude verbond, deel 3 (1933)", "url": "https://www.dbnl.org/tekst/_hei009heil11_01/_hei009heil11_01_0140.php", "scope": "Esther 15:1; 16:1–24", "transcriptionSha256": hashlib.sha256(supplement_raw).hexdigest(), "license": "Public domain", "rightsEvidence": reviewed.get("rightsEvidence", [])},
        ],
        "verseIdentityUncertainBooks": ORDER,
        "bookCount": len(books), "oldTestamentBookCount": 46, "newTestamentBookCount": 27,
        "chapterCount": sum(len(b["chapters"]) for b in books), "verseCount": sum(len(c["verses"]) for b in books for c in b["chapters"]),
        "textSha256": CATHOLIC.text_hash(books),
        "catholicNavigation": [
            {"book": "EST", "chapter": 10, "verse": 4, "label": "Esther additions"},
            {"book": "DAN", "chapter": 3, "verse": 24, "label": "Prayer and song in Daniel"},
            {"book": "DAN", "chapter": 13, "verse": 1, "label": "Susanna"},
            {"book": "DAN", "chapter": 14, "verse": 1, "label": "Bel and the dragon"},
            {"book": "BAR", "chapter": 6, "verse": 1, "label": "Letter of Jeremiah"},
        ],
    }
    return {"meta": meta, "books": books}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=pathlib.Path, default=ROOT / ".cache" / "nld1939_usfx.zip")
    parser.add_argument("--osis", type=pathlib.Path, default=ROOT / ".cache" / "Canisius-7083841.xml")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = import_dutch(download(args.source, BASE_URL), download(args.osis, OSIS_URL))
    serialized = json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n"
    if args.check:
        if DESTINATION.read_text(encoding="utf-8") != serialized:
            raise SystemExit("Dutch Catholic artifact differs from the reviewed sources; regenerate it.")
    else:
        DESTINATION.write_text(serialized, encoding="utf-8")
    print(json.dumps({"file": str(DESTINATION), "books": data["meta"]["bookCount"], "chapters": data["meta"]["chapterCount"], "verses": data["meta"]["verseCount"], "textSha256": data["meta"]["textSha256"]}))


if __name__ == "__main__":
    main()
