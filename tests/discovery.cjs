const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const context={window:{}};
vm.createContext(context);
const root=path.resolve(__dirname,'..');
vm.runInContext(fs.readFileSync(path.join(root,'dist/data.js'),'utf8'),context);
vm.runInContext(fs.readFileSync(path.join(root,'dist/discovery.js'),'utf8'),context);
const Model=context.window.BibleDiscovery,model=new Model(context.window.BIBLE_DATA);
const one=model.neighborhood({focusId:'abraham',depth:1});
const two=model.neighborhood({focusId:'abraham',depth:2});
const three=model.neighborhood({focusId:'abraham',depth:3});
assert.ok(two.people.length>one.people.length,'Zooming out must reveal new relatives');
assert.ok(three.people.length>two.people.length,'Deeper zoom must continue discovery');
assert.ok(two.relationships.length>one.relationships.length);
assert.equal(Model.depthForZoom(.8,.8),1);
assert.equal(Model.depthForZoom(.8/1.5,.8),2);
assert.equal(Model.depthForZoom(.8/2.25,.8),3);
assert.equal(Model.depthForZoom(1.2,.8),1,'Close zoom maps to one relationship step');
assert.equal(Model.depthForZoom(.00001,.8),8,'Discovery is bounded');
const local=model.neighborhood({focusId:'abraham',depth:1,localRoots:['terah']});
assert.ok(local.people.length>one.people.length,'Zooming in on Terah must reveal his nearby relatives');
const localIds=new Set(local.people.map(p=>p.id));
assert.ok(one.people.every(p=>localIds.has(p.id)),'Local discovery must retain previously visible people');
assert.ok(local.relationships.every(e=>localIds.has(e.source)&&localIds.has(e.target)));
const bounded=model.neighborhood({focusId:'abraham',depth:Infinity,limit:25});
assert.equal(bounded.people.length,25);
assert.ok(bounded.omitted>0,'Large branches explicitly report additional people');
const ids=new Set(bounded.people.map(p=>p.id));
assert.ok(bounded.relationships.every(e=>ids.has(e.source)&&ids.has(e.target)));
const noSpouses=model.neighborhood({focusId:'abraham',depth:2,spouses:false});
assert.ok(noSpouses.relationships.every(e=>e.type!=='spouse'));
const nt=model.neighborhood({focusId:'jesus',depth:8,testament:'NT'});
assert.ok(nt.people.every(p=>model.allows(p,'NT')));
assert.equal(model.neighborhood({focusId:'abraham',depth:3,testament:'NT'}).people.length,0);
const disconnected=context.window.BIBLE_DATA.people.find(p=>model.byPerson.get(p.id).length===0);
assert.ok(disconnected);
assert.equal(model.neighborhood({focusId:disconnected.id,depth:8}).people.length,1,'Isolated people must remain explorable without invented links');
console.log(`Discovery passed: Abraham expands ${one.people.length} → ${two.people.length} → ${three.people.length} people; caps, testaments, spouse visibility and disconnected records verified.`);
